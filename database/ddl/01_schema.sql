-- 01_schema.sql
-- Proyecto: Sistema Integral de Gestion Farmaceutica
-- Motor objetivo: Oracle Database XE
-- Baseline: Documento 09 v1.3 Final (15 tablas)
-- Este script crea las tablas y columnas. Las restricciones se agregan en 02_constraints.sql.

CREATE TABLE ROL (
    id_rol        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre        VARCHAR2(50) NOT NULL,
    descripcion   VARCHAR2(150),
    activo        CHAR(1) DEFAULT 'S' NOT NULL
);

CREATE TABLE SUCURSAL (
    id_sucursal    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR2(100) NOT NULL,
    tipo_sucursal  VARCHAR2(30) NOT NULL,
    departamento   VARCHAR2(50) NOT NULL,
    municipio      VARCHAR2(50) NOT NULL,
    direccion      VARCHAR2(200) NOT NULL,
    activa         CHAR(1) DEFAULT 'S' NOT NULL
);

CREATE TABLE USUARIO (
    id_usuario      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_rol          NUMBER(10) NOT NULL,
    id_sucursal     NUMBER(10),
    nombre          VARCHAR2(100) NOT NULL,
    correo          VARCHAR2(120) NOT NULL,
    password_hash   VARCHAR2(255) NOT NULL,
    activo          CHAR(1) DEFAULT 'S' NOT NULL,
    fecha_creacion  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE MEDICAMENTO (
    id_medicamento  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    codigo          VARCHAR2(30) NOT NULL,
    nombre          VARCHAR2(120) NOT NULL,
    categoria       VARCHAR2(60) NOT NULL,
    presentacion    VARCHAR2(80) NOT NULL,
    precio          NUMBER(10,2) NOT NULL,
    activo          CHAR(1) DEFAULT 'S' NOT NULL
);

CREATE TABLE INVENTARIO (
    id_inventario        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_sucursal          NUMBER(10) NOT NULL,
    id_medicamento       NUMBER(10) NOT NULL,
    existencia           NUMBER(10) DEFAULT 0 NOT NULL,
    fecha_actualizacion  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE MOVIMIENTO_INVENTARIO (
    id_movimiento    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_inventario    NUMBER(10) NOT NULL,
    id_usuario       NUMBER(10) NOT NULL,
    tipo_movimiento  VARCHAR2(30) NOT NULL,
    cantidad         NUMBER(10) NOT NULL,
    saldo_anterior   NUMBER(10) NOT NULL,
    saldo_nuevo      NUMBER(10) NOT NULL,
    referencia       VARCHAR2(100),
    fecha            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE TRANSFERENCIA (
    id_transferencia       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_sucursal_origen     NUMBER(10) NOT NULL,
    id_sucursal_destino    NUMBER(10) NOT NULL,
    id_usuario             NUMBER(10) NOT NULL,
    fecha                  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    estado                 VARCHAR2(20) NOT NULL,
    observacion            VARCHAR2(250)
);

CREATE TABLE DETALLE_TRANSFERENCIA (
    id_detalle        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_transferencia  NUMBER(10) NOT NULL,
    id_medicamento    NUMBER(10) NOT NULL,
    cantidad          NUMBER(10) NOT NULL
);

CREATE TABLE VENTA (
    id_venta       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_sucursal    NUMBER(10) NOT NULL,
    id_usuario     NUMBER(10) NOT NULL,
    fecha          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    forma_pago     VARCHAR2(20) NOT NULL,
    total          NUMBER(12,2) NOT NULL,
    estado         VARCHAR2(20) NOT NULL
);

CREATE TABLE DETALLE_VENTA (
    id_detalle       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_venta         NUMBER(10) NOT NULL,
    id_medicamento   NUMBER(10) NOT NULL,
    cantidad         NUMBER(10) NOT NULL,
    precio_unitario  NUMBER(10,2) NOT NULL,
    subtotal         NUMBER(12,2) NOT NULL
);

CREATE TABLE MOVIMIENTO_CAJA (
    id_mov_caja   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_sucursal   NUMBER(10) NOT NULL,
    id_usuario    NUMBER(10) NOT NULL,
    id_venta      NUMBER(10),
    tipo          VARCHAR2(10) NOT NULL,
    monto         NUMBER(12,2) NOT NULL,
    concepto      VARCHAR2(200) NOT NULL,
    fecha         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE ACTIVO_FIJO (
    id_activo       NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_sucursal     NUMBER(10) NOT NULL,
    categoria       VARCHAR2(60) NOT NULL,
    descripcion     VARCHAR2(150) NOT NULL,
    valor           NUMBER(12,2) NOT NULL,
    estado          VARCHAR2(20) NOT NULL,
    responsable     VARCHAR2(100),
    fecha_registro  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE GASTO_PLANILLA (
    id_gasto        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_sucursal     NUMBER(10) NOT NULL,
    id_usuario      NUMBER(10) NOT NULL,
    periodo         VARCHAR2(7) NOT NULL,
    concepto        VARCHAR2(120) NOT NULL,
    monto           NUMBER(12,2) NOT NULL,
    fecha_registro  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE ENTREGA (
    id_entrega        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_venta          NUMBER(10) NOT NULL,
    id_sucursal       NUMBER(10) NOT NULL,
    nombre_cliente    VARCHAR2(100) NOT NULL,
    telefono          VARCHAR2(20) NOT NULL,
    direccion         VARCHAR2(200) NOT NULL,
    departamento      VARCHAR2(50) NOT NULL,
    municipio         VARCHAR2(50) NOT NULL,
    tiempo_estimado   NUMBER(5),
    estado            VARCHAR2(20) NOT NULL,
    fecha_solicitud   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    fecha_entrega     TIMESTAMP,
    observaciones     VARCHAR2(250)
);

CREATE TABLE AUDITORIA (
    id_auditoria  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY,
    id_usuario    NUMBER(10),
    id_sucursal   NUMBER(10),
    modulo        VARCHAR2(50) NOT NULL,
    accion        VARCHAR2(50) NOT NULL,
    entidad       VARCHAR2(50) NOT NULL,
    id_entidad    NUMBER(10) NOT NULL,
    descripcion   VARCHAR2(500) NOT NULL,
    fecha_hora    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
